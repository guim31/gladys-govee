// Colour temperature range of the models that do not accept the 2000-9000 K of
// the Govee LAN API documentation (measured by the library users).
export const KELVIN_RANGES = {
  H6076: [2700, 6500],
  H60A1: [2200, 6500],
  H612F: [2800, 9000],
  H61B3: [2000, 7200],
};

// The range the Govee LAN API documents for `colorwc`.
export const DEFAULT_KELVIN_RANGE = [2000, 9000];

/**
 * Capabilities of a model, from its SKU (e.g. "H6008").
 *
 * An unknown SKU gets the full set the Govee LAN API documents for every
 * LAN-enabled device (on/off, brightness, colour, colour temperature), flagged
 * `known: false` so the logs can ask for a report; scenes stay off, since their
 * codes are only verified on the listed models.
 * @param {string} sku
 */
export function modelCapabilities(sku) {
  const key = String(sku ?? '').toUpperCase();
  const flags = MODEL_FLAGS[key];
  const kelvinRange = KELVIN_RANGES[key] ?? DEFAULT_KELVIN_RANGE;
  if (flags === undefined) {
    return {
      known: false,
      rgb: true,
      kelvin: true,
      brightness: true,
      scenes: false,
      kelvinRange: DEFAULT_KELVIN_RANGE,
    };
  }
  return {
    known: true,
    rgb: flags.includes('r'),
    kelvin: flags.includes('k'),
    brightness: flags.includes('b'),
    scenes: flags.includes('s'),
    kelvinRange,
  };
}
